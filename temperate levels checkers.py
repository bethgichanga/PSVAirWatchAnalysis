import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import classification_report
from sklearn.preprocessing import StandardScaler
from google.colab import drive

# Mount Google Drive
drive.mount('/content/drive')

# Load the dataset from Google Drive
data_path = '/content/drive/My Drive/temperature_readings.xlsx'
data = pd.read_excel(data_path)

# Replace numeric labels with categorical labels
data["Label"] = data["Label"].map({0: "safe", 1: "warning", 2: "danger"})

# Features and labels
X = data[["Temperature"]]
y = data["Label"]

# Standardize the temperature values
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

# Split the data into training and testing sets
X_train, X_test, y_train, y_test = train_test_split(X_scaled, y, test_size=0.2, random_state=42)

# Train a Random Forest Classifier
model = RandomForestClassifier(random_state=42)
model.fit(X_train, y_train)

# Evaluate the model
y_pred = model.predict(X_test)
print(classification_report(y_test, y_pred))

# Save the trained model to Google Drive
import joblib
model_path = '/content/drive/My Drive/temperature_monitor_model.pkl'
joblib.dump(model, model_path)

# Load and use the model (example)
loaded_model = joblib.load(model_path)
sample_temperature = scaler.transform([[]])  # Example input
prediction = loaded_model.predict(sample_temperature)
print("Prediction:", prediction)

