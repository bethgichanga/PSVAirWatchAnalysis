# Step 5: Apply KMeans clustering to divide the data into 3 clusters
kmeans = KMeans(n_clusters=3)
clusters = kmeans.fit_predict(scaled_temp_data)

# Step 6: Map clusters to colors (green for safe, blue for warning, red for danger)
color_map = {0: 'green', 1: 'blue', 2: 'red'}
colors = [color_map[cluster] for cluster in clusters]

# Step 7: Create the scatter plot
plt.figure(figsize=(10, 6))
plt.scatter(df.index, df['Temperature'], c=colors, marker='o', edgecolors='black', s=100)

# Step 8: Label the plot
